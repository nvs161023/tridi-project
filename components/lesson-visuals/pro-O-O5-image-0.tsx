import { VisualWrapper, type VisualProps } from "./_Wrapper";

const FONT = "system-ui, -apple-system, sans-serif";

/**
 * Ступень воронки: имя шага, вопрос из text урока и ширина трапеции сверху и
 * снизу. Ступени идут вплотную, поэтому низ одной равен верху следующей — правый
 * край воронки получается одной ломаной линией, а не набором прямоугольников.
 */
type Step = {
  name: string;
  /** Вопрос урока; у шестой ступени не вопрос, а итог выбора. */
  question: string;
  topW: number;
  bottomW: number;
  color: string;
};

/** Воронка: левый край 14, шесть ступеней по 19 от 22 до 136. */
const FUNNEL_X = 14;
const STEP_TOP = 22;
const STEP_H = 19;
const QUESTION_GAP = 6;

/** Кто из шагов про требования, кто про железо, кто про выбор: цвет по паре. */
const STEPS: Step[] = [
  { name: "1 задача", question: "что печатать?", topW: 210, bottomW: 186, color: "#38bdf8" },
  { name: "2 бюджет", question: "сколько готов потратить?", topW: 186, bottomW: 162, color: "#38bdf8" },
  { name: "3 технология", question: "FDM или SLA?", topW: 162, bottomW: 138, color: "#34d399" },
  { name: "4 размер", question: "какой стол?", topW: 138, bottomW: 114, color: "#34d399" },
  { name: "5 материалы", question: "какие нужны?", topW: 114, bottomW: 90, color: "#fbbf24" },
  { name: "6 модель", question: "какая модель?", topW: 90, bottomW: 66, color: "#fbbf24" },
];

/** Скрытые расходы — text урока: в одну строку не влезают, поэтому их две. */
const HIDDEN = [
  "скрытые расходы: пластик 1500 ₽/кг · сопла 200 ₽ · стол 2000 ₽",
  "инструменты 3000 ₽ · сушилка 5000 ₽ · камера 3000 ₽ → +15 000 ₽",
];

/**
 * «Дерево выбора» — шесть шагов урока одной воронкой: задача, бюджет,
 * технология, размер, материалы, модель. Каждая ступень ниже и уже предыдущей,
 * поэтому кадр читается сверху вниз как сужение выбора, а не как список.
 *
 * Ровно по content: «Схема: задача → бюджет → технология → размер → материалы →
 * модель», вопросы справа — из text урока слово в слово («что печатать?», «сколько
 * готов потратить?», «FDM или SLA?», «какой стол?», «какие нужны?»). Шестая
 * ступень вопроса не имеет: в тексте она названа итогом, поэтому у неё стоит
 * результат «под задачу и бюджет». Числа внизу — text «Скрытые расходы», а
 * последняя строка — tip про 20–30 тыс. и warning про б/у с проверкой ремней.
 *
 * Нарисована воронка, а не дерево с ветками: в content шаги соединены стрелками
 * цепочки, ветвей в тексте блока нет. От O3-image-0 (четыре квадранта) и
 * O4-image-0 (стойка принтеров) отличается тем, что предмет не перечисляется, а
 * сужается: шесть трапеций с общим правым склоном и подписями по краю. От
 * U-U3-image-0 и M-M2-image-0 (сравнение полосами) — тем, что полосы тут не
 * сравниваются по длине, а образуют одну фигуру; от L-L1-image-0 (дорожки с
 * финишем) — отсутствием трасс.
 *
 * Кадр статичный: это image-блок, движения в нём нет.
 */
export function ProOO5Image0({ title, animated }: VisualProps) {
  return (
    <VisualWrapper
      title={title}
      ariaLabel="Схема выбора принтера воронкой из шести шагов: задача — что печатать, бюджет — сколько готов потратить, технология — FDM или SLA, размер — какой стол, материалы — какие нужны, модель — какая модель и под задачу с бюджетом. Каждая ступень ниже и уже предыдущей, поэтому выбор сужается сверху вниз. Внизу скрытые расходы поверх цены принтера: пластик 1500 рублей за килограмм, сопла 200, стол 2000, инструменты 3000, сушилка 5000, камера 3000 — плюс 15 000 рублей к бюджету старта; и совет не брать первый принтер дорогим, а начать с 20–30 тысяч."
      animated={animated}
    >
      <svg viewBox="0 0 320 180" className="w-full h-full" aria-hidden="true" fontFamily={FONT}>
        <rect x="0.5" y="0.5" width="319" height="179" rx="12" fill="#1e293b" fillOpacity="0.5" stroke="#475569" />
        <text x="12" y="15" fontSize="10" fill="#94a3b8">
          выбор принтера: шесть шагов, каждый сужает поиск
        </text>

        {/* Воронка: шесть трапеций вплотную, правый склон — одна ломаная */}
        {STEPS.map((step, index) => {
          const top = STEP_TOP + index * STEP_H;
          const mid = (step.topW + step.bottomW) / 2;
          return (
            <g key={step.name}>
              <polygon
                points={`${FUNNEL_X},${top} ${FUNNEL_X + step.topW},${top} ${FUNNEL_X + step.bottomW},${top + STEP_H} ${FUNNEL_X},${top + STEP_H}`}
                fill={step.color}
                fillOpacity="0.16"
                stroke={step.color}
                strokeOpacity="0.8"
              />
              <text x={FUNNEL_X + 8} y={top + 12} fontSize="7.5" fontWeight="bold" fill="#e2e8f0">
                {step.name}
              </text>
              <text x={FUNNEL_X + mid + QUESTION_GAP} y={top + 13} fontSize="7.5" fill="#94a3b8">
                {step.question}
              </text>
            </g>
          );
        })}

        <text x="190" y="136" fontSize="7.5" fill="#6ee7b7">
          под задачу и бюджет
        </text>
        {HIDDEN.map((line, index) => (
          <text key={line} x="12" y={148 + index * 12} fontSize="7.5" fill="#94a3b8">
            {line}
          </text>
        ))}
        <text x="12" y="172" fontSize="7.5" fill="#94a3b8">
          не бери первый принтер дорогим: начни с 20–30 тыс. ₽
        </text>
      </svg>
    </VisualWrapper>
  );
}

