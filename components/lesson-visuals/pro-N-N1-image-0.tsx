/**
 * Центрирование подписи под колонкой: ширину считаем по 0.55em — той же
 * оценкой, что и проверка читаемости (text-anchor в кадрах курса не используем).
 */
function centerX(cx: number, text: string, size: number): number {
  return Math.round((cx - (text.length * size * 0.55) / 2) * 10) / 10;
}

