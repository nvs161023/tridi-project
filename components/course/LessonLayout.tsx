import type { ReactNode } from "react";

/**
 * Раскладка страницы урока — одна на все четыре уровня.
 *
 * Зачем узкая колонка: урок читают, а не просматривают. На широком мониторе
 * строка во всю ширину (прежние `max-w-6xl`) уводила глаз к правому краю, и
 * начало следующей строки приходилось искать заново. Теперь текст живёт в
 * колонке до 800px — это примерно 70–80 знаков в строке при 17–18px, как в
 * книге. Колонка стоит по центру страницы, а шапка урока ограничена тем же
 * пределом, поэтому заголовок, текст и карточки блоков идут по одной левой
 * линии.
 *
 * Внутри `LessonBlocks` ни один блок не ограничен своей `max-w-*`: абзац,
 * список и шаги тянутся от края до края карточки — ширину задаёт эта колонка.
 * Отступы прежние — `px-5 py-12`, с `sm` — `px-8 py-16`, поэтому на телефоне
 * текст не прилипает к краям (390 − 40 = 350px строки).
 */
export function LessonLayout({ children }: { children: ReactNode }) {
  return (
    <main className="mx-auto w-full max-w-[800px] px-5 py-12 sm:px-8 sm:py-16">
      {children}
    </main>
  );
}
