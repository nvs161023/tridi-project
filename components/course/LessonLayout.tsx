import type { ReactNode } from "react";

/**
 * Раскладка страницы урока — одна на все четыре уровня.
 *
 * Зачем: раньше урок был одной узкой колонкой по центру (`max-w-3xl`), и на
 * широком мониторе треть ширины слева и справа оставалась пустой — начало каждой
 * строки приходилось искать заново. Теперь текст занимает всю страницу: `main`
 * шириной до `max-w-6xl` — ровно столько же, сколько у шапки урока, поэтому
 * заголовок, текст и карточки блоков стоят на одной левой линии и доходят до
 * одной правой.
 *
 * Оглавление «В этом уроке» справа убрано: колонка 15–17rem отнимала ширину у
 * текста и делила страницу на две части, а на ноутбуке 1280 текст из-за неё
 * оставался узким. Разделы урока видны по заголовкам самих карточек, так что
 * ориентир никуда не делся.
 *
 * Внутри `LessonBlocks` ни один блок не ограничен своей `max-w-*`: абзац, список
 * и шаги тянутся от края до края карточки. Отступы прежние — `px-5 py-12`,
 * с `sm` — `px-8 py-16`, поэтому на телефоне вид не меняется, а на широком
 * экране строка просто становится длиннее.
 */
export function LessonLayout({ children }: { children: ReactNode }) {
  return (
    <main className="mx-auto max-w-6xl px-5 py-12 sm:px-8 sm:py-16">
      {children}
    </main>
  );
}
