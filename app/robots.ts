import type { MetadataRoute } from "next";

import { SITE_URL } from "@/lib/seo";

/**
 * robots.txt: индексируем публичные страницы и закрываем личные разделы.
 *
 * Запрет в robots.txt не заменяет проверку доступа: /dashboard, /admin,
 * /course/ и /certificate всё равно закрыты middleware и серверными проверками.
 * Правило лишь просит робота не тратить обход на страницы, которые ему не
 * покажут.
 *
 * `/course/` указан с косой чертой намеренно. Строки robots.txt сравниваются с
 * началом пути, поэтому прежнее правило `/course` закрывало заодно продающие
 * лендинги `/courses/confident`, `/courses/engineer`, `/courses/profit` и
 * `/courses/pro` — при том что все четыре есть в карте сайта с priority 0.9.
 * С косой чертой закрытыми остаются только уроки и служебные страницы курса
 * (`/course/lesson-1`, `/course/check`), а `/courses/*` открыт для обхода.
 *
 * `/constructor`, `/3d-generator` и `/gallery` для поиска открыты: это витрины
 * инструментов платформы, они перечислены в карте сайта и описывают, что умеет
 * сервис. Сам экспорт STL и скачивание моделей по-прежнему требуют входа и
 * оплаты — robots.txt отвечает за индексацию, а не за доступ.
 *
 * Центр инструментов, справочник дефектов и библиотека профилей публичные и
 * есть в карте сайта, поэтому /tools и /profiles разрешены явно — чтобы
 * будущий запрет по ошибке не отрезал страницы, которые мы хотим показывать
 * в поиске.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",
        allow: ["/", "/tools", "/profiles", "/blog"],
        disallow: [
          "/api/",
          // Служебные файлы сборки: индексировать нечего, а обход тратит
          // краулинговый бюджет.
          "/_next/",
          "/admin",
          "/dashboard",
          // Косая черта в конце — не опечатка: без неё правило закрывает и
          // продающие страницы /courses/* (см. комментарий выше).
          "/course/",
          "/certificate",
          "/verify",
        ],
      },
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
