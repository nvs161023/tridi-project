/**
 * Состояние формы авторизации — то, что Server Action возвращает в браузер.
 *
 * Server Action не хранит состояние между запросами (каждый запрос независим),
 * поэтому «что показать пользователю» он возвращает значением: либо текст
 * ошибки, либо сообщение (например, «подтвердите email»). Если ни того, ни
 * другого нет — форма просто ждёт действий пользователя.
 */
export type AuthFormState = {
  error?: string;
  info?: string;
  /**
   * То, что пользователь уже ввёл. Нужно потому, что React сбрасывает обычные
   * (неконтролируемые) поля после отправки формы — без этого после ошибки входа
   * человеку пришлось бы заново печатать email. Пароль сюда НЕ попадает.
   */
  values?: {
    name?: string;
    email?: string;
  };
};

/** Стартовое состояние формы: сообщать нечего. */
export const emptyAuthFormState: AuthFormState = {};
