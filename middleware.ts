import { type NextRequest } from "next/server";

import { updateSession } from "@/lib/supabase/middleware";

/**
 * Прослойка для путей, где важна авторизация.
 *
 * Работает на защищённых страницах (/dashboard, /course/*) и на страницах входа
 * (/auth/*), и делает четыре вещи: продлевает сессию Supabase (если access-токен
 * истёк), отправляет гостя на вход с запоминанием адреса (next=...), уводит
 * авторизованного пользователя со страницы входа туда, куда он шёл, и передаёт
 * данные пользователя странице заголовком.
 *
 * Список путей задаётся в config.matcher ниже — middleware не запускается на
 * всём остальном сайте.
 *
 * Публичные страницы (главная и /subscription) сюда не попадают: им сессия не
 * нужна, а вызов updateSession для авторизованного пользователя — это сетевой
 * запрос к Supabase. Раньше он выполнялся на каждом переходе по сайту и заметно
 * тормозил навигацию. Гостю сеть не нужна и сейчас: без cookie сессии Supabase
 * отвечает «пользователь не найден» сразу.
 *
 * Уроки защищены: кнопка «Начать курс бесплатно» на главной ведёт на
 * /course/lesson-1, и гость видит страницу входа, а не содержимое урока.
 *
 * Логика лежит в lib/supabase/middleware.ts (функция updateSession) — здесь
 * только подключение. Не заменяйте возвращаемый ответ: в нём едут обновлённые
 * cookies, потеряв их, пользователя будет разлогинивать.
 */
export async function middleware(request: NextRequest) {
  return await updateSession(request);
}

export const config = {
  /**
   * Покрываем защищённые разделы и страницы авторизации:
   *  - /dashboard и всё, что внутри;
   *  - /course/* — уроки курса, без входа недоступны;
   *  - /auth/* (вход, регистрация и всё, что внутри).
   *
   * `:path*` означает «ноль и более сегментов», поэтому "/dashboard/:path*"
   * захватывает и сам /dashboard — отдельная запись "/dashboard" не нужна.
   *
   * Публичные страницы (/, /subscription) в matcher не перечислены: для них
   * middleware не запускается вообще, то есть нет ни обращения к Supabase,
   * ни задержки перед отдачей HTML.
   *
   * Когда появится /constructor — добавьте "/constructor/:path*".
   */
  matcher: ["/dashboard/:path*", "/course/:path*", "/auth/:path*"],
};

