/**
 * Силуэты брелока: реестр пресетов.
 *
 * Встроенных силуэтов больше нет: четырнадцать прежних (`dog_tag`, `hexagon`,
 * `cat`, …) выглядели примитивно и удалены. Пресет — не SVG-строка, а описание
 * формы: идентификатор, подпись, пояснение и три размера по умолчанию. Геометрия
 * каждого пресета строится кодом в lib/constructor/keychain-preset-geometry.ts;
 * готовые перечислены в `IMPLEMENTED_KEYCHAIN_PRESETS`. Единственная оставшаяся
 * SVG-форма — запасной жетон для своего контура
 * (lib/constructor/keychain-fallback-shape.ts): он показывается, пока файл не
 * разобрался, и в печать не уходит.
 *
 * Размеры пресета лежат внутри границ слайдеров брелока
 * (`CONSTRUCTOR_LIMITS.length` 30–100, `width` 20–50, `thickness` 2–5 с шагом
 * 0.5 мм), чтобы выбор пресета никогда не выталкивал панель в недопустимое
 * значение. Единственное исключение — QR-визитка: её габариты заданы размером
 * кода, а не слайдером, и нормализация выводит ширину с высотой из панельного
 * выбора `qrCardSize` (60 × 40 или 70 × 45 мм). `defaultHeight` — это прежняя
 * «длина» сверху вниз: ушко под кольцо входит в этот габарит.
 */

/** Идентификаторы девяти силуэтов; порядок задаёт порядок в списке. */
export const KEYCHAIN_PRESET_IDS = [
  "apple-tag",
  "capsule",
  "hex",
  "gear",
  "brick",
  "ticket",
  "starburst",
  "heart",
  "qr-card",
] as const;

export type KeychainPresetId = (typeof KEYCHAIN_PRESET_IDS)[number];

/**
 * Позиция отверстия Ø5 мм под кольцо.
 *
 * Одно значение на все пресеты вместо отдельных полей вроде `qrCardTab`: панель,
 * состояние модели и API читают одно имя, поэтому позиция не может разойтись
 * между предпросмотром и файлом. Какой набор доступен — решает не пользователь, а
 * силуэт: у Starburst боковой стенки нет вовсе, у Brick боковое отверстие ломает
 * шип. Набор лежит в реестре (`holePlacements`), обоснование — в
 * `hole-placement-audit.md`.
 *
 * - `center` — по оси симметрии, как было у всех пресетов;
 * - `left` / `right` — то же отверстие, сдвинутое от оси к левой или правой кромке;
 * - `none` — отверстия нет: брелок печатается без ушка;
 * - `tab` — проушина Ø11 мм выступает над верхней кромкой (в работе, T3).
 */
export const HOLE_PLACEMENTS = [
  "center",
  "left",
  "right",
  "none",
  "tab",
] as const;

export type HolePlacement = (typeof HOLE_PLACEMENTS)[number];

/** Подписи позиций для выпадающего списка «Отверстие». */
export const HOLE_PLACEMENT_LABELS: Record<HolePlacement, string> = {
  center: "По центру",
  left: "Слева",
  right: "Справа",
  none: "Без отверстия",
  tab: "Проушина сверху",
};

/** Проверка значения из состояния или API: только пять известных позиций. */
export function isHolePlacement(value: unknown): value is HolePlacement {
  return (
    typeof value === "string" &&
    (HOLE_PLACEMENTS as readonly string[]).includes(value)
  );
}

/** Описание одного силуэта: что за форма и с каких размеров её начинать. */
export type KeychainPreset = {
  /** Идентификатор в реестре и в состоянии панели. */
  id: KeychainPresetId;
  /** Название в выпадающем списке: короткое, чтобы влезало на мобильном. */
  label: string;
  /** Пояснение под списком: чем форма отличается от соседних. */
  description: string;
  /** Ширина в самой широкой части, мм. */
  defaultWidth: number;
  /** Высота сверху вниз, мм; ушко под кольцо входит в габарит. */
  defaultHeight: number;
  /** Толщина основы, мм: задаёт прочность ушка и глубину рельефа. */
  defaultThickness: number;
  /**
   * Центр кармана под NFC-метку по Y, мм; нет поля — пресет карман не держит.
   *
   * Карман — круг Ø29.8 мм глубиной 1 мм, открытый снизу: метку вкладывают в
   * паузу печати, и верхние слои закрывают её пластиком. Центр выбран по
   * вписанному в силуэт кругу: от него до ближайшей свободной точки не меньше
   * 14.9 мм, поэтому стенка вокруг метки Ø26 мм не тоньше 1.5 мм. Числа получены
   * растром настоящей геометрии пресетов — расчёт и таблица в
   * `nfc-compatibility.md`.
   *
   * Поле стоит в реестре, а не считается на лету: растеризация силуэта в панели
   * на каждый рендер стоила бы десятки миллисекунд, а промах центра на полтора
   * миллиметра уже рвёт стенку. Обратная сторона — при правке силуэта число надо
   * перепроверить тем же скриптом (`scripts/tmp-nfc-fit.mjs`).
   */
  nfcPocketY?: number;
  /**
   * Позиции отверстия под кольцо, которые держит силуэт.
   *
   * Порядок массива задаёт порядок пунктов в панели. Пустой список — пресет живёт
   * своим креплением (QR-визитка: проушина или отверстие в теле через
   * `qrCardTab`) и в общем механизме не участвует. Числа-обоснования — в
   * `hole-placement-audit.md`: у Apple Tag боковая стенка 2.5 мм, у Starburst
   * боковой стенки нет (−2.00 мм), а шип Brick режет боковую стенку в −0.73 мм,
   * поэтому `left`/`right` у них не предлагаются вовсе.
   */
  holePlacements: HolePlacement[];
};

