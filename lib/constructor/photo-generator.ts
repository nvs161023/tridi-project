/**
 * Настройки генератора 3D по фото для панели конструктора.
 *
 * `/api/generate-3d` принимает 1–4 снимка и качество, а считает модель сеть:
 * клиент только создаёт задачу, а потом опрашивает `/api/check-3d-status`.
 * Числа и правило выбора сети живут здесь, чтобы интерфейс не дублировал их
 * по разметке: лимит фото, интервал опроса и сжатие — одна точка правки.
 */

/** Качество генерации: то же поле `quality`, что принимает роут. */
export type GeneratorQuality = "standard" | "ultra";

/** Сеть, которая считает задачу: её же нужно опрашивать по статусу. */
export type GeneratorService = "tripo" | "meshy";

/** Больше четырёх фото сеть не принимает: это виды одной модели, не галерея. */
export const MAX_GENERATOR_PHOTOS = 4;

/** Виды по порядку загрузки: он же порядок кадров у Tripo multiview. */
export const GENERATOR_PHOTO_VIEWS = [
  "спереди",
  "слева",
  "сзади",
  "справа",
] as const;

/** Интервал опроса статуса: три секунды, как в задании. */
export const GENERATOR_POLL_INTERVAL_MS = 3_000;

/**
 * Сколько ждём готовую модель.
 *
 * Ультра-задача Meshy считается минуты, а первый успешный опрос ещё и режет
 * сетку до 100 000 треугольников. Десять минут — с запасом; дольше держать
 * пользователя у прогресс-бара смысла нет.
 */
export const GENERATOR_POLL_TIMEOUT_MS = 10 * 60 * 1_000;

/**
 * Длинная сторона фото после сжатия в браузере.
 *
 * Сеть строит модель по силуэту, а не по пикселям: 1600 px хватает, зато
 * четыре кадра с телефона не превращаются в 60 МБ base64.
 */
export const GENERATOR_PHOTO_MAX_SIDE_PX = 1_600;

/** Плотность JPEG при сжатии: 0.9 сохраняет края и не раздувает base64. */
export const GENERATOR_PHOTO_JPEG_QUALITY = 0.9;

/**
 * Сеть по числу фото и качеству.
 *
 * Правило повторяет `chooseProvider` из `/api/generate-3d`: несколько фото
 * умеет сопоставлять только Tripo (multiview), одно фото в ультре отдаётся
 * Meshy, одно в стандарте — дешёвой Tripo. Клиент обязан опрашивать ту сеть,
 * которая создала задачу, иначе номер не найдётся.
 */
export function generatorServiceFor(
  photoCount: number,
  quality: GeneratorQuality,
): GeneratorService {
  if (photoCount > 1) {
    return "tripo";
  }

  return quality === "ultra" ? "meshy" : "tripo";
}
