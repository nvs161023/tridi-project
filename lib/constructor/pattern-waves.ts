/**
 * Математические узоры рельефа: соты, чешуйки, плетение, шеврон, муар и
 * каннелюры.
 *
 * Функции чистые и без three.js: они получают безразмерные координаты
 * u (по окружности) и v (по высоте) и возвращают смещение в диапазоне −1…1.
 * Геометрия вазы сама переводит миллиметры в эти координаты, поэтому
 * узор масштабируется вместе с высотой и диаметром. Модуль отдельный,
 * чтобы формулы можно было проверить без сборки сцены.
 *
 * Координата u — это уже готовая фаза `угол × частота` (целое число периодов на
 * оборот обязательно: иначе шов окружности не сойдётся и сварка не склеит
 * стенку). v — высота, переведённая в те же единицы, что и дуга окружности:
 * `высота × частота / опорный радиус`. Там, где формула зависит от v, ячейки
 * остаются квадратными при любом диаметре.
 */

import type { VasePattern } from "@/lib/constructor/params";

/** Отношение высоты равностороннего треугольника к стороне. */
const SQRT3 = Math.sqrt(3);

/**
 * Насколько резко соты переходят от ячейки к рёбрам.
 *
 * Сумма трёх косинусов даёт плавные волны. Гиперболический тангенс сжимает
 * середину и растягивает края: получаются плоские ячейки с чёткими стенками.
 * Без сжатия рельеф выглядел бы как обычные волны, а не как соты.
 */
const HONEYCOMB_SHARPNESS = 2.4;

/**
 * Насколько плоско плетение «корзина».
 *
 * Произведение двух синусов даёт плавные полосы, которые сходятся в ноль и
 * текут друг в друга. Гиперболический тангенс сжимает синус: у полосы
 * появляется ровная середина и резкий край, и плетение читается как полосы
 * «над-под», а не как мелкая сетка. 1.6 — полоса занимает около половины
 * периода и остаётся шире шага сетки.
 */
const BASKET_SHARPNESS = 1.6;

/** Максимум одного множителя плетения до нормировки: `tanh(BASKET_SHARPNESS)`. */
const BASKET_PEAK = Math.tanh(BASKET_SHARPNESS);

/**
 * Глубина излома шеврона в радианах фазы.
 *
 * Это размах, на который треугольная волна по высоте сдвигает полосу по кругу:
 * 1.15 рад даёт плечо галочки около 66° к горизонту. Меньше — полосы почти
 * вертикальные, как у рёбер; больше π — галочка складывается в петлю, и на
 * вершине появляется ступенька.
 */
const CHEVRON_DEPTH_RAD = 1.15;

/**
 * Показатель степени жёлоба каннелюры.
 *
 * 0.5 — корень из модуля синуса: у нуля функция растёт бесконечно круто, у
 * единицы выходит на площадку. Именно поэтому дно жёлоба получается узким и
 * острым, а гребень между жёлобами — широким.
 */
const FLUTE_EDGE_POWER = 0.5;

/**
 * Во сколько раз «соты» и «чешуйки» мельче, чем рёбра при той же частоте.
 *
 * У рёбер и спирали частота — это число гребней по окружности. Для сот и
 * чешуек та же частота давала бы слишком крупные ячейки, поэтому она
 * удваивается. Множитель целый: на шве окружности (φ = 2π) фаза должна
 * совпасть с фазой в нуле, иначе сварка не склеит шов.
 */
export const DETAIL_PATTERN_SCALE = 2;

/**
 * Шестиугольный рельеф «соты», значение −1…1.
 *
 * Три косинусоиды с волновыми векторами, повёрнутыми друг к другу на 60°,
 * складываются в картину с шестикратной симметрией: максимумы образуют
 * треугольную решётку, а линии уровня — шестиугольники. v берётся в тех же
 * единицах, что u, поэтому ячейки остаются правильными, а не вытянутыми.
 */
export function honeycombWave(u: number, v: number): number {
  const lattice =
    (Math.cos(u) +
      Math.cos(0.5 * u + (SQRT3 / 2) * v) +
      Math.cos(-0.5 * u + (SQRT3 / 2) * v)) /
    3;

  return Math.tanh(HONEYCOMB_SHARPNESS * lattice) / Math.tanh(HONEYCOMB_SHARPNESS);
}

/**
 * Рельеф «чешуйки», значение −1…1.
 *
 * Две волны с разными фазами накладываются друг на друга: синус сдвигается
 * синусом по высоте и загибается вбок, а косинус идёт по диагонали. Их сумма
 * даёт ряд перекрывающихся чешуек — каждая следующая волна начинается там, где
 * предыдущая уже пошла на спад.
 */
export function scalesWave(u: number, v: number): number {
  const scallop = Math.sin(u + Math.sin(v));
  const overlapping = Math.cos(v - 0.5 * u);

  return 0.5 * (scallop + overlapping);
}

/**
 * Плетение «корзина», значение −1…1.
 *
 * Произведение двух сжатых синусоид: по окружности `sin(u)`, по высоте
 * `cos(v)`. Там, где полоса одной решётки переходит через ноль, вторая задаёт
 * её знак — получается шахматка «над-под», как у плетёной корзины, а не
 * решётка из ромбов. Делитель возвращает диапазон: каждый множитель не больше
 * `tanh(BASKET_SHARPNESS)`, поэтому произведение нормируется его квадратом.
 */
export function basketWave(u: number, v: number): number {
  const around = Math.tanh(BASKET_SHARPNESS * Math.sin(u));
  const vertical = Math.tanh(BASKET_SHARPNESS * Math.cos(v));

  return (around * vertical) / (BASKET_PEAK * BASKET_PEAK);
}

/**
 * Треугольная волна −1…1: половину периода растёт, половину падает.
 *
 * `asin(sin v)` даёт «пилу» с изломами на вершинах, умножение на `2/π`
 * растягивает её до единицы. Излом здесь принципиален: гладкий синус дал бы
 * волну, а шеврон — это именно галочка со сломом.
 */
function triangleWave(phase: number): number {
  return (2 / Math.PI) * Math.asin(Math.sin(phase));
}

/**
 * Шевроны (галочки), значение −1…1.
 *
 * Наклонная полоса — это синус с фазой, зависящей от высоты: `sin(u + k·v)`.
 * Здесь `k·v` — треугольная волна, поэтому полоса идёт вверх, ломается в
 * вершине галочки и уходит вниз; следующий ряд повторяет то же выше.
 * `CHEVRON_DEPTH_RAD` задаёт крутизну плеча.
 */
export function chevronWave(u: number, v: number): number {
  return Math.sin(u + CHEVRON_DEPTH_RAD * triangleWave(v));
}

/**
 * Муар, значение −1…1.
 *
 * Две решётки под прямым углом: `sin(u)` по окружности и `sin(v)` по высоте.
 * Их произведение — интерференция: на пересечении нулевых линий получается
 * ромбическая сетка, максимумы складываются в пятна. Поверх второго слоя или
 * сетки печати те же пятна дают биения крупнее обеих решёток — это и есть муар.
 * Обе решётки целые по окружности, поэтому шов сходится.
 */
export function moireWave(u: number, v: number): number {
  return Math.sin(u) * Math.sin(v);
}

/**
 * Каннелюры узором, значение −1…1.
 *
 * `|sin(u/2)|^0.5` — та же частота, что у рёбер (у модуля вдвое больше нулей,
 * поэтому жёлобов столько же, сколько гребней у рёбер), но форма другая: у нуля
 * корень растёт бесконечно круто, у единицы выходит на площадку. Получаются
 * узкие острые жёлоба и широкие гребни — не синусоида рёбер, а колонна.
 * Значение растянуто с 0…1 на −1…1, чтобы амплитуда слоя значила то же, что у
 * остальных узоров.
 *
 * Дно жёлоба — излом, поэтому сетка обязана попасть в него вершиной: за это
 * отвечает шаг `patternSegmentStep` в `vase-budget.ts`. Без него выборка
 * проходит мимо дна и жёлоб выходит вдвое мельче заданного.
 */
export function flutesWave(u: number): number {
  return 2 * Math.pow(Math.abs(Math.sin(u / 2)), FLUTE_EDGE_POWER) - 1;
}

/**
 * Во сколько раз узор дробит частоту слайдера.
 *
 * Соты и чешуйки считают частоту вдвое мельче (`DETAIL_PATTERN_SCALE`): при той
 * же цифре ячейка должна быть мельче гребня. Остальным узорам частота — это
 * ровно число полос, жёлобов или галочек по окружности. Множитель целый, иначе
 * на шве окружности (`φ = 2π`) фаза не совпала бы с нулём и сварка не склеила
 * бы стенку.
 */
export function patternFrequencyScale(pattern: VasePattern): number {
  return pattern === "honeycomb" || pattern === "scales"
    ? DETAIL_PATTERN_SCALE
    : 1;
}

/**
 * Зависит ли узор от высоты в единицах длины, а не в миллиметрах.
 *
 * Соты, чешуйки, плетение, шеврон и муар строят рисунок в двух направлениях,
 * поэтому высоту им приходится переводить в те же единицы, что и дугу
 * окружности — для этого геометрия ищет опорный радиус в сетке. Рёбрам,
 * спирали, волнам и каннелюрам высота нужна либо в миллиметрах, либо не нужна
 * вовсе: лишний поиск радиуса по десяткам тысяч вершин им ни к чему.
 */
export function patternUsesHeightSpacing(pattern: VasePattern): boolean {
  return (
    pattern === "honeycomb" ||
    pattern === "scales" ||
    pattern === "basket" ||
    pattern === "chevron" ||
    pattern === "moire"
  );
}
