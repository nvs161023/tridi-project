/**
 * Математические узоры рельефа: соты и чешуйки.
 *
 * Функции чистые и без three.js: они получают безразмерные координаты
 * u (по окружности) и v (по высоте) и возвращают смещение в диапазоне −1…1.
 * Геометрия вазы сама переводит миллиметры в эти координаты, поэтому
 * узор масштабируется вместе с высотой и диаметром. Модуль отдельный,
 * чтобы формулы можно было проверить без сборки сцены.
 */

/** Отношение высоты равностороннего треугольника к стороне. */
const SQRT3 = Math.sqrt(3);

/**
 * Насколько резко соты переходят от ячейки к рёбрам.
 *
 * Сумма трёх косинусов даёт плавные волны. Гиперболический тангенс сжимает
 * середину и растягивает края: получаются плоские ячейки с чёткими стенками.
 * Без сжатия рельеф выглядел бы как обычные волны, а не как соты.
 */
const HONEYCOMB_SHARPNESS = 2.4;

/**
 * Во сколько раз «соты» и «чешуйки» мельче, чем рёбра при той же частоте.
 *
 * У рёбер и спирали частота — это число гребней по окружности. Для сот и
 * чешуек та же частота давала бы слишком крупные ячейки, поэтому она
 * удваивается. Множитель целый: на шве окружности (φ = 2π) фаза должна
 * совпасть с фазой в нуле, иначе сварка не склеит шов.
 */
export const DETAIL_PATTERN_SCALE = 2;

/**
 * Шестиугольный рельеф «соты», значение −1…1.
 *
 * Три косинусоиды с волновыми векторами, повёрнутыми друг к другу на 60°,
 * складываются в картину с шестикратной симметрией: максимумы образуют
 * треугольную решётку, а линии уровня — шестиугольники. v берётся в тех же
 * единицах, что u, поэтому ячейки остаются правильными, а не вытянутыми.
 */
export function honeycombWave(u: number, v: number): number {
  const lattice =
    (Math.cos(u) +
      Math.cos(0.5 * u + (SQRT3 / 2) * v) +
      Math.cos(-0.5 * u + (SQRT3 / 2) * v)) /
    3;

  return Math.tanh(HONEYCOMB_SHARPNESS * lattice) / Math.tanh(HONEYCOMB_SHARPNESS);
}

/**
 * Рельеф «чешуйки», значение −1…1.
 *
 * Две волны с разными фазами накладываются друг на друга: синус сдвигается
 * синусом по высоте и загибается вбок, а косинус идёт по диагонали. Их сумма
 * даёт ряд перекрывающихся чешуек — каждая следующая волна начинается там, где
 * предыдущая уже пошла на спад.
 */
export function scalesWave(u: number, v: number): number {
  const scallop = Math.sin(u + Math.sin(v));
  const overlapping = Math.cos(v - 0.5 * u);

  return 0.5 * (scallop + overlapping);
}
