/**
 * Разделы сайта, которые готовы не полностью и потому скрыты от всех.
 *
 * Зачем отдельный модуль: правило должно жить в одном месте. Его читают
 * middleware (редирект до всякой проверки сессии) и сама страница (вторая
 * линия защиты на случай запроса мимо middleware). Если правило разъедется,
 * получится либо дыра (страница открыта), либо мёртвая ссылка в навигации.
 *
 * Сейчас список пуст: конструктор 3D вернулся 6 ноября 2026. Владелец снимает
 * ограничение раньше проверки всех моделей на печати осознанно — решение за
 * качеством принимается вручную, а старые генераторы (вазы, литофаны, коробки)
 * остаются видимыми до пересборки. Адрес `/constructor` больше не скрыт: он
 * снова обычная страница под входом (список защищённых путей —
 * lib/supabase/middleware.ts), ссылки на него стоят в шапке и в центре
 * инструментов.
 *
 * Механизм оставлен на будущее: если раздел снова окажется неготовым, путь
 * достаточно добавить в список — middleware начнёт отдавать редирект до всякой
 * проверки сессии. Отдаём редирект, а не 404: адрес мог остаться в закладках, и
 * «страница не найдена» читалась бы как поломка сайта. Ведём в центр
 * инструментов — там остальные рабочие разделы.
 *
 * Когда раздел доделан: убрать путь из списка и вернуть его в
 * PROTECTED_PATH_PREFIXES (lib/supabase/middleware.ts), если нужен вход.
 */
export const HIDDEN_PATH_PREFIXES: readonly string[] = [];

/** Куда уводим со скрытого адреса. */
export const HIDDEN_REDIRECT_PATH = "/tools";

/**
 * Лежит ли путь в скрытом разделе: сам раздел и всё под ним.
 * `/constructor` и `/constructor/anything` — да, `/constructors` — нет.
 */
export function isHiddenPath(pathname: string): boolean {
  return HIDDEN_PATH_PREFIXES.some(
    (prefix) => pathname === prefix || pathname.startsWith(`${prefix}/`),
  );
}
