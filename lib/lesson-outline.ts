/**
 * Оглавление урока для колонки «В этом уроке» на странице урока.
 *
 * Зачем: урок — это десятки блоков, и по ходу чтения не видно, сколько разделов
 * ещё впереди и где стоит практика. Оглавление собирается из заголовков блоков:
 * заголовок блока и есть раздел урока.
 *
 * Якорь пункта — порядковый номер блока (`lessonBlockAnchor`), и тот же номер
 * вешает на карточку блока `components/course/LessonBlocks.tsx`. Источник один,
 * поэтому ссылка не разъедется с блоком, даже если в данные добавят новый блок:
 * номер считается по массиву блоков, а не хранится в JSON.
 *
 * Блок без заголовка в оглавление не попадает — у него нет раздела, а безымянный
 * пункт только путает. Если подписать почти нечего (меньше трёх заголовков),
 * оглавление не показывается вовсе: короткий урок читается и без него.
 *
 * Типы данных — в lib/types.ts (LessonBlock). Здесь только числа и подписи.
 */
import type { LessonBlock } from "@/lib/types";

/** Пункт оглавления: якорь блока и его заголовок. */
export type LessonOutlineItem = {
  /** Идентификатор блока в разметке — `lesson-block-3`. */
  id: string;
  /** Заголовок блока: он же текст пункта оглавления. */
  title: string;
};

/** Сколько заголовков нужно, чтобы оглавление было полезнее пустоты. */
const MIN_OUTLINE_ITEMS = 3;

/** Идентификатор блока урока: номер блока с единицы (нулевой индекс — в первый). */
export function lessonBlockAnchor(index: number): string {
  return `lesson-block-${index + 1}`;
}

/**
 * Оглавление по блокам урока.
 *
 * Пустой массив — «оглавление не нужно»: страница в этом случае не рисует
 * правую колонку, а текст остаётся в той же широкой раскладке.
 */
export function lessonOutline(blocks: LessonBlock[]): LessonOutlineItem[] {
  const items = blocks.flatMap((block, index) => {
    const title = block.title?.trim();

    return title ? [{ id: lessonBlockAnchor(index), title }] : [];
  });

  return items.length >= MIN_OUTLINE_ITEMS ? items : [];
}
